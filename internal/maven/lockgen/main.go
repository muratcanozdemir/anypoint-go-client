// Command lockgen pins a Java tool's classpath: it resolves the given
// artifacts and writes one "sha256 url" line per jar, which the CLI
// downloads and checks at run time.
//
//	go run ./internal/maven/lockgen -o cmd/anypoint/tooling/amf.lock com.github.amlorg:amf-cli_2.12:5.16.13199
package main

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/muratcanozdemir/anypoint-go-client/internal/maven"
)

func main() {
	out := flag.String("o", "", "lock file to write (default stdout)")
	repos := flag.String("repos", "https://repo.maven.apache.org/maven2,https://repository-master.mulesoft.org/nexus/content/repositories/releases,https://repository-master.mulesoft.org/nexus/content/repositories/public",
		"comma-separated repositories, searched in order")
	flag.Parse()
	if err := run(*out, strings.Split(*repos, ","), flag.Args()); err != nil {
		fmt.Fprintln(os.Stderr, "lockgen:", err)
		os.Exit(1)
	}
}

func run(out string, repos, roots []string) error {
	ctx := context.Background()
	r := &maven.Resolver{Repos: repos}
	seen := map[string]bool{}
	var lines []string
	for _, s := range roots {
		root, err := maven.ParseCoord(s)
		if err != nil {
			return err
		}
		cp, err := r.Resolve(ctx, root)
		if err != nil {
			return err
		}
		for _, c := range cp {
			path := c.Path("jar")
			if seen[path] {
				continue
			}
			seen[path] = true
			repo, b, err := r.Locate(ctx, path)
			if err != nil {
				return err
			}
			sum := sha256.Sum256(b)
			lines = append(lines, hex.EncodeToString(sum[:])+" "+strings.TrimRight(repo, "/")+"/"+path)
			fmt.Fprintf(os.Stderr, "%s (%d KB)\n", c, len(b)/1024)
		}
	}
	sort.Strings(lines)
	doc := "# generated by: go run ./internal/maven/lockgen " + strings.Join(roots, " ") + "\n" + strings.Join(lines, "\n") + "\n"
	if out == "" {
		_, err := os.Stdout.WriteString(doc)
		return err
	}
	return os.WriteFile(out, []byte(doc), 0o600)
}
