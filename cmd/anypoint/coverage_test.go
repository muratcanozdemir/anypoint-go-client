package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite docs/coverage.md")

// pendingPlugins are anypoint-cli-v4 plugins whose commands are still being
// added; TestCoverage only reports their gaps. The list shrinks to empty.
var pendingPlugins = map[string]bool{}

type v4Spec struct {
	Plugins map[string]struct {
		Version  string `json:"version"`
		Commands map[string]struct {
			Args  []string `json:"args"`
			Flags []string `json:"flags"`
		} `json:"commands"`
	} `json:"plugins"`
}

// status of one v4 command in this CLI.
type status struct {
	plugin, id, state, note string
}

// TestCoverage checks every anypoint-cli-v4 command in spec/ against the
// command tree: it must resolve to a command that accepts all its flags, or
// be registered as unsupported with a reason.
func TestCoverage(t *testing.T) {
	t.Setenv("ANYPOINT_TOOLING_DIR", t.TempDir())
	t.Setenv("ANYPOINT_NPM_REGISTRY", "http://127.0.0.1:1") // never fetch
	t.Setenv("XDG_CACHE_HOME", t.TempDir())
	b, err := os.ReadFile("../../spec/anypoint-cli-v4.json")
	if err != nil {
		t.Fatal(err)
	}
	var spec v4Spec
	if err := json.Unmarshal(b, &spec); err != nil {
		t.Fatal(err)
	}
	root := commands()
	var all []status
	for plugin, p := range spec.Plugins {
		for id, c := range p.Commands {
			st := status{plugin: plugin, id: id}
			node, _, rest, err := resolve(root, []string{id})
			switch {
			case err != nil || node.Run == nil || len(rest) > 0:
				st.state = "missing"
			case node.unsupported != "":
				st.state, st.note = "unsupported", node.unsupported
			default:
				st.state = "done"
				if missing := missingFlags(id, c.Flags); len(missing) > 0 {
					st.state, st.note = "missing flags", strings.Join(missing, ", ")
				}
			}
			all = append(all, st)
		}
	}
	sort.Slice(all, func(i, j int) bool {
		if all[i].plugin != all[j].plugin {
			return all[i].plugin < all[j].plugin
		}
		return all[i].id < all[j].id
	})
	gaps := 0
	for _, s := range all {
		if s.state == "done" || s.state == "unsupported" {
			continue
		}
		if pendingPlugins[s.plugin] {
			gaps++
			continue
		}
		t.Errorf("%s (%s): %s %s", s.id, s.plugin, s.state, s.note)
	}
	if gaps > 0 {
		t.Logf("%d commands in pending plugins are not covered yet", gaps)
	}
	if *update {
		if err := os.WriteFile("../../docs/coverage.md", coverageDoc(spec, all), 0o600); err != nil {
			t.Fatal(err)
		}
	}
}

// missingFlags returns the v4 flags that `anypoint ID -h` does not list.
func missingFlags(id string, flags []string) []string {
	var out, errOut bytes.Buffer
	err := runContext(context.Background(), []string{id, "-h"}, &out, &errOut)
	if err != nil && !errors.Is(err, errHelp) {
		return []string{"(-h failed: " + err.Error() + ")"}
	}
	help := errOut.String() + out.String()
	var missing []string
	for _, f := range flags {
		if !strings.Contains(help, "-"+f+" ") {
			missing = append(missing, f)
		}
	}
	return missing
}

func coverageDoc(spec v4Spec, all []status) []byte {
	var b bytes.Buffer
	b.WriteString("# anypoint-cli-v4 coverage\n\n")
	b.WriteString("Generated by `go test ./cmd/anypoint -run TestCoverage -update` from `spec/anypoint-cli-v4.json`.\n")
	b.WriteString("Every command can be run as `anypoint topic:command` or `anypoint topic command`.\n\n")
	counts := map[string]map[string]int{}
	for _, s := range all {
		if counts[s.plugin] == nil {
			counts[s.plugin] = map[string]int{}
		}
		counts[s.plugin][s.state]++
	}
	var plugins []string
	for p := range spec.Plugins {
		plugins = append(plugins, p)
	}
	sort.Strings(plugins)
	b.WriteString("| plugin | version | commands | done | unsupported | to do |\n|---|---|---|---|---|---|\n")
	for _, p := range plugins {
		c := counts[p]
		todo := len(spec.Plugins[p].Commands) - c["done"] - c["unsupported"]
		fmt.Fprintf(&b, "| %s | %s | %d | %d | %d | %d |\n", p, spec.Plugins[p].Version, len(spec.Plugins[p].Commands), c["done"], c["unsupported"], todo)
	}
	plugin := ""
	for _, s := range all {
		if s.plugin != plugin {
			plugin = s.plugin
			fmt.Fprintf(&b, "\n## %s\n\n| command | status | note |\n|---|---|---|\n", plugin)
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", s.id, s.state, strings.ReplaceAll(s.note, "|", "\\|"))
	}
	return b.Bytes()
}
